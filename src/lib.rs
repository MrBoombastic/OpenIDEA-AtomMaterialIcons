//! Path icons for Atom Material Icons (plugin API 1.8).
//!
//! The icon theme (`icons/theme.json`) handles almost every Atom Material rule. OpenIDEA refuses
//! the 44 source regexes that look at the folder a file is in (`.*/tests?/.*\.java$`) or repeat a
//! group, so this component matches those with Rust's regex-automata (linear time) and gives the
//! files their icons by path with `decorations.set-file-icons`. It follows Atom Material's order:
//! the highest-priority matching rule wins (the first one on a tie), and only when that rule is one
//! of the 44 does the file get an icon here.

use std::cell::{OnceCell, RefCell};
use std::collections::{BTreeMap, HashMap};

use openidea_plugin::{
    Context, Error, Event, EventKind, FileKind, Invocation, LogLevel, Plugin, Project, host,
    register_plugin,
};
use regex_automata::util::syntax;
use regex_automata::{Anchored, Input, MatchKind, meta};

/// `{ "globs": [...], "rules": [[priority, regex, icon id or ""], ...] }`, best rule first.
/// Generated by tools/convert_atom_material.mjs.
const RULES: &str = include_str!("../rules/path-icons.json");
/// Files listed per glob and project.
const MAX_FILES: u32 = 100_000;
/// Icons per project. The host allows 10,000 per set and 4 MiB of decorations per plugin.
const MAX_ICONS: usize = 5_000;
const SETTING: &str = "pathIcons";

/// Rules matched against the file name, or against `/` + the project-relative path (the ones
/// containing `/`), as one automaton each.
struct Matcher {
    regex: meta::Regex,
    /// Pattern id -> index in `Rules::icons`.
    rules: Vec<usize>,
}

impl Matcher {
    fn new(patterns: &[(usize, &str)]) -> Result<Self, String> {
        let wrapped: Vec<String> = patterns.iter().map(|(_, p)| format!("^(?:{p})$")).collect();
        let regex = meta::Builder::new()
            // Leftmost-first over anchored patterns reports the lowest pattern id that matches,
            // which is the best rule. A large lazy-DFA cache keeps 1,700 patterns fast.
            .configure(meta::Config::new().match_kind(MatchKind::LeftmostFirst).hybrid_cache_capacity(16 << 20))
            .syntax(syntax::Config::new().case_insensitive(true).unicode(false).utf8(false))
            .build_many(&wrapped)
            .map_err(|e| e.to_string())?;
        Ok(Self { regex, rules: patterns.iter().map(|(i, _)| *i).collect() })
    }

    fn best(&self, haystack: &str) -> Option<usize> {
        let found = self.regex.find(Input::new(haystack).anchored(Anchored::Yes))?;
        Some(self.rules[found.pattern().as_usize()])
    }
}

pub struct Rules {
    globs: Vec<String>,
    /// Per rule, best first: `Some(icon)` for the rules matched here, `None` for the rules the
    /// icon theme already handles.
    icons: Vec<Option<String>>,
    names: Matcher,
    paths: Matcher,
}

impl Rules {
    pub fn parse(json: &str) -> Result<Self, String> {
        let value: serde_json::Value = serde_json::from_str(json).map_err(|e| e.to_string())?;
        let globs = value["globs"]
            .as_array()
            .ok_or("globs missing")?
            .iter()
            .filter_map(|g| g.as_str().map(str::to_owned))
            .collect();
        let (mut icons, mut names, mut paths) = (Vec::new(), Vec::new(), Vec::new());
        for (i, rule) in value["rules"].as_array().ok_or("rules missing")?.iter().enumerate() {
            let pattern = rule[1].as_str().ok_or("rule regex missing")?;
            icons.push(rule[2].as_str().filter(|icon| !icon.is_empty()).map(str::to_owned));
            if pattern.contains('/') { &mut paths } else { &mut names }.push((i, pattern));
        }
        Ok(Self { globs, icons, names: Matcher::new(&names)?, paths: Matcher::new(&paths)? })
    }

    pub fn globs(&self) -> &[String] {
        &self.globs
    }

    /// The icon for a project-relative file path (`/` separators), when the best matching rule
    /// (Atom Material: highest priority, the first one on a tie) is one matched here.
    pub fn icon(&self, relative: &str) -> Option<&str> {
        let relative = relative.trim_start_matches('/');
        let name = relative.rsplit('/').next().unwrap_or(relative);
        let by_name = self.names.best(name);
        let by_path = self.paths.best(&format!("/{relative}"));
        let best = match (by_name, by_path) {
            (Some(a), Some(b)) => a.min(b),
            (a, b) => a.or(b)?,
        };
        self.icons[best].as_deref()
    }
}

/// `C:\a\b` and `C:/a/b` alike, without a trailing separator.
fn normalize(path: &str) -> String {
    path.replace('\\', "/").trim_end_matches('/').to_owned()
}

/// `path` relative to `root`, when it is inside it.
fn relative<'a>(root: &str, path: &'a str) -> Option<String> {
    let path = normalize(path);
    let rest = path.strip_prefix(root)?.strip_prefix('/')?;
    (!rest.is_empty()).then(|| rest.to_owned())
}

/// One decoration set per project: setting a set replaces it everywhere.
fn set_id(root: &str) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in root.bytes() {
        hash = (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3);
    }
    format!("path-icons-{hash:016x}")
}

fn enabled() -> bool {
    host::setting_bool(SETTING).unwrap_or(true)
}

fn log(message: &str) {
    host::log(LogLevel::Warn, message);
}

#[derive(Default)]
struct PathIcons {
    rules: OnceCell<Rules>,
    /// Icons per project root (normalized), as last sent: absolute path as the host gave it -> icon.
    projects: RefCell<HashMap<String, BTreeMap<String, String>>>,
}

impl PathIcons {
    fn rules(&self) -> &Rules {
        self.rules.get_or_init(|| Rules::parse(RULES).expect("rules/path-icons.json is generated"))
    }

    fn publish(&self, root: &str, icons: &BTreeMap<String, String>) -> Result<(), Error> {
        let items: Vec<(String, String)> = icons.iter().map(|(p, i)| (p.clone(), i.clone())).collect();
        host::set_file_icons(&set_id(root), &items)
    }

    /// Lists the project's candidate files and sends their icons.
    fn scan(&self, project: &Project) -> Result<(), Error> {
        let root = normalize(&project.root()?);
        let rules = self.rules();
        let task = host::begin_task("Atom Material path icons", false);
        let mut icons = BTreeMap::new();
        'globs: for (n, glob) in rules.globs().iter().enumerate() {
            task.report(n as u32, Some(rules.globs().len() as u32), None);
            for file in project.find_files(glob, MAX_FILES)? {
                let Some(rel) = relative(&root, &file) else { continue };
                if let Some(icon) = rules.icon(&rel) {
                    icons.insert(file, icon.to_owned());
                    if icons.len() >= MAX_ICONS {
                        log(&format!("{root}: only the first {MAX_ICONS} path icons are shown"));
                        break 'globs;
                    }
                }
            }
        }
        self.publish(&root, &icons)?;
        self.projects.borrow_mut().insert(root, icons);
        Ok(())
    }

    fn scan_all(&self) {
        let Ok(projects) = host::projects() else { return };
        for project in projects {
            if let Err(e) = self.scan(&project) {
                log(&format!("path icons: {e}"));
            }
        }
    }

    fn clear_all(&self) {
        let roots: Vec<String> = host::projects()
            .unwrap_or_default()
            .iter()
            .filter_map(|p| p.root().ok().map(|r| normalize(&r)))
            .chain(self.projects.borrow().keys().cloned())
            .collect();
        for root in roots {
            let _ = host::clear_file_decorations(&set_id(&root));
        }
        self.projects.borrow_mut().clear();
    }

    /// Scans the project of `path` unless it was scanned in this instance.
    fn ensure(&self, path: &str) {
        let Some(project) = host::project_of(path) else { return };
        let Ok(root) = project.root() else { return };
        if !self.projects.borrow().contains_key(&normalize(&root)) {
            if let Err(e) = self.scan(&project) {
                log(&format!("path icons: {e}"));
            }
        }
    }

    /// Created and removed files: updated in place when the project was scanned in this
    /// instance; a new folder (a rename or a move) or an unknown project is scanned again.
    fn files_changed(&self, created: &[String], removed: &[String]) {
        let mut touched: BTreeMap<String, Project> = BTreeMap::new();
        for path in created.iter().chain(removed) {
            if let Some(project) = host::project_of(path) {
                if let Ok(root) = project.root() {
                    touched.entry(normalize(&root)).or_insert(project);
                }
            }
        }
        for (root, project) in touched {
            let known = self.projects.borrow().contains_key(&root);
            let new_folder = created.iter().any(|p| {
                relative(&root, p).is_some()
                    && project.stat(p).is_ok_and(|s| s.kind == FileKind::Directory)
            });
            if !known || new_folder {
                if let Err(e) = self.scan(&project) {
                    log(&format!("path icons: {e}"));
                }
                continue;
            }
            let mut projects = self.projects.borrow_mut();
            let Some(icons) = projects.get_mut(&root) else { continue };
            let before = icons.clone();
            for path in removed {
                let folder = format!("{}/", normalize(path));
                icons.retain(|p, _| p != path && !normalize(p).starts_with(&folder));
            }
            for path in created {
                let Some(rel) = relative(&root, path) else { continue };
                if icons.len() >= MAX_ICONS {
                    break;
                }
                if let Some(icon) = self.rules().icon(&rel) {
                    icons.insert(path.clone(), icon.to_owned());
                }
            }
            if *icons != before {
                if let Err(e) = self.publish(&root, icons) {
                    log(&format!("path icons: {e}"));
                }
            }
        }
    }
}

impl Plugin for PathIcons {
    fn activate(&mut self, _ctx: &Context) -> Result<(), Error> {
        for kind in [EventKind::FilesChanged, EventKind::FileOpened, EventKind::SettingsChanged] {
            host::subscribe(kind)?;
        }
        // At start-up (`on-startup-finished`) and after the instance was reclaimed for being idle,
        // when its record of what it sent is gone. Projects opened later are scanned on their
        // first opened file.
        if enabled() {
            self.scan_all();
        }
        Ok(())
    }

    fn run_command(&mut self, id: &str, _ctx: &Invocation, _arg: Option<&str>) -> Result<Option<String>, Error> {
        match id {
            "refresh-path-icons" => {
                if !enabled() {
                    return Ok(Some("Icons by folder are turned off in the plugin's settings.".into()));
                }
                self.projects.borrow_mut().clear();
                self.scan_all();
                Ok(None)
            }
            _ => Err(Error::NotFound(id.into())),
        }
    }

    fn handle_events(&mut self, events: &[Event], _ctx: &Invocation) {
        let on = enabled();
        for event in events {
            match event {
                Event::Other { kind, data } if kind == "settings-changed" => {
                    if data.contains(SETTING) {
                        if on {
                            self.scan_all();
                        } else {
                            self.clear_all();
                        }
                    }
                }
                _ if !on => {}
                Event::FilesChanged(changes) => self.files_changed(&changes.created, &changes.removed),
                Event::FileOpened(path) => self.ensure(path),
                _ => {}
            }
        }
    }
}

register_plugin!(PathIcons);

#[cfg(test)]
mod tests {
    use super::*;

    fn rules() -> Rules {
        Rules::parse(RULES).unwrap()
    }

    #[test]
    fn every_rule_compiles() {
        let value: serde_json::Value = serde_json::from_str(RULES).unwrap();
        for rule in value["rules"].as_array().unwrap() {
            let pattern = rule[1].as_str().unwrap();
            Matcher::new(&[(0, pattern)]).unwrap_or_else(|e| panic!("{pattern}: {e}"));
        }
    }

    /// The combined automata pick the same rule as trying every rule in order.
    #[test]
    fn same_as_rule_by_rule() {
        let rules = rules();
        let value: serde_json::Value = serde_json::from_str(RULES).unwrap();
        let single: Vec<(bool, Matcher)> = value["rules"]
            .as_array()
            .unwrap()
            .iter()
            .map(|r| {
                let p = r[1].as_str().unwrap();
                (p.contains('/'), Matcher::new(&[(0, p)]).unwrap())
            })
            .collect();
        let names = [
            "package.json", "index.ts", "en.json", "foo.test.ts", "Main.java", "FooTest.java", "README.md",
            "compose.yaml", "settings.json", ".eslintrc.json", "user.reducer.ts", "user.ts", "a.py", "conftest.py",
            "Gruntfile.js", "app.module.ts", "x.rb", "routes.rb", "x.dart", "x.php", "jest.config.js", "y.yml",
        ];
        let folders = ["", "src/", "src/test/java/", "tests/", "config/", "locales/", "store/reducers/", "spec/", "eslint/", "app/models/"];
        for folder in folders {
            for name in names {
                let path = format!("{folder}{name}");
                let full = format!("/{path}");
                let naive = single.iter().position(|(by_path, m)| m.best(if *by_path { &full } else { name }).is_some());
                let expected = naive.and_then(|i| rules.icons[i].as_deref());
                assert_eq!(rules.icon(&path), expected, "{path}");
            }
        }
    }

    #[test]
    fn folder_rules() {
        let rules = rules();
        for (path, icon) in [
            ("src/test/java/com/acme/FooTest.java", Some("testjavafiles")),
            ("src/main/java/com/acme/Foo.java", None),
            ("tests/test_api.py", Some("testpyfiles")),
            ("app/tests/models.rb", Some("testrubyfiles")),
            ("spec/components/Button.tsx", Some("testreactfiles")),
            ("src/store/reducers/user.ts", Some("ngrx-reducers-files")),
            ("src/locales/messages.json", Some("i18nlangfiles")),
            // A two-letter name (priority 90) outranks the folder rule (50).
            ("src/locales/en.json", Some("i18nlang")),
            ("src/i18n/messages.yml", Some("i18nlangfiles")),
            ("en.json", Some("i18nlang")),
            ("config/custom.json", Some("preferencesfiles")),
            ("config/database.yml", None),
            ("project/.husky/install.mjs", Some("huskyfiles")),
            ("docker/services.yaml", Some("dockercomposefiles")),
            ("lib/bloc/counter.dart", Some("blocfiles")),
            ("test/a.js", Some("testjsfiles")),
            ("src/actions/user.ts", Some("ngrx-actions-files")),
            ("src/sagas/user.ts", Some("redux-saga-files")),
            ("src/routes/home.tsx", Some("routesfiles")),
            (".storybook/preview.js", Some("storybookfiles")),
            (".kitchen.local.yml", Some("kitchenci")),
            ("mootools-core-1.4.5.js", Some("mootools")),
            (".renovaterc", Some("renovate")),
            ("renovate", None),
            ("behat.local.yml", Some("behatconfig")),
            ("icomoon.min.json", Some("icomoon")),
            ("cordova-2.1.js", Some("cordova")),
            ("cordova.js", Some("cordova")),
            ("raphael.min.no-deps.js", Some("raphael")),
            ("README.md", None),
            ("main.ts", None),
        ] {
            assert_eq!(rules.icon(path), icon, "{path}");
        }
    }

    #[test]
    fn higher_priority_rules_win() {
        let rules = rules();
        // Exact-name rules (priority 100) beat folder rules (50), as in Atom Material.
        assert_eq!(rules.icon("tests/package.json"), None);
        assert_eq!(rules.icon("config/tsconfig.json"), None);
        assert_eq!(rules.icon("tests/jest.config.js"), None);
    }

    #[test]
    fn paths() {
        assert_eq!(relative("C:/p", r"C:\p\src\a.ts").as_deref(), Some("src/a.ts"));
        assert_eq!(relative("C:/p", "C:/pq/a.ts"), None);
        assert_eq!(relative("/home/u/p", "/home/u/p"), None);
        assert_ne!(set_id("C:/a"), set_id("C:/b"));
        assert!(set_id("C:/a").len() <= 128);
    }
}
